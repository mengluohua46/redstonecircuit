package com.jiangyuefengyu.redstonecircuit.mixin;

import com.jiangyuefengyu.redstonecircuit.client.ShaderCompat;

import net.minecraft.client.resources.model.BakedModel;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.block.state.BlockState;

import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * The Sodium half of "leave the host block out of the chunk mesh".
 *
 * <h2>Why a second mixin</h2>
 * Sodium does not build its meshes through vanilla's {@code BlockRenderDispatcher.renderBatched} - it
 * has its own chunk renderer and never calls that method - so the vanilla hook does nothing for the
 * people most likely to be running a shader pack in the first place. This is its per-block entry
 * point, confirmed by disassembling {@code sodium-fabric 0.8.13+mc1.21.1}: {@code
 * ChunkBuilderMeshingTask#execute} loops over the section's 16x16x16 blocks and, for every one that is
 * not air, calls
 * {@code BlockRenderer#renderModel(BakedModel, BlockState, BlockPos, BlockPos)} - the descriptor below
 * is that call site, read out of the bytecode rather than guessed.
 *
 * <h2>How it can name a class it does not depend on</h2>
 * The target is a string, not a class literal, and the four parameters are all vanilla types, so the
 * source needs no Sodium anywhere on the compile classpath. Whether the mixin is applied at all is
 * decided by {@link SodiumMixinPlugin}, which asks the classpath - so a player without Sodium never
 * loads this class and never sees the target resolved. (Sodium is on the <em>compile</em> classpath
 * as of this round, but only so that the build can check this file's claims: nothing here references a
 * Sodium type, and the built jar neither needs nor declares Sodium.)
 *
 * <h2>Why this hook used to do nothing, and why it does now</h2>
 * The method descriptor above is written in Mojang's names - {@code BakedModel}, {@code BlockState},
 * {@code BlockPos} - because that is what this source is compiled against. At runtime the same classes
 * are named intermediary ({@code class_1087}, {@code class_2680}, {@code class_2338}) and the target
 * class is <em>not</em> obfuscated, so Mixin has to be told the translation. That translation lives in
 * a refmap, and the refmap is generated by Loom's Mixin annotation processor. The processor was off
 * (see {@code build.gradle}), so the jar shipped no refmap at all: Mixin looked for
 * {@code renderModel(Lnet/minecraft/client/resources/model/BakedModel;...)V} on a class whose real
 * method is {@code renderModel(Lnet/minecraft/class_1087;...)V}, found no candidate, and - because of
 * {@code require = 0} below - said nothing. No crash, no "Mixin apply failed" line, just a block that
 * stayed in the chunk mesh. The processor is on now, so the jar carries
 * {@code redstonecircuit-fabric-refmap.json}, both mixin configs name it, and the refmap holds exactly
 * this entry:
 *
 * <pre>
 * "renderModel(Lnet/minecraft/client/resources/model/BakedModel;...)V"
 *     -&gt; "Lnet/caffeinemc/.../pipeline/BlockRenderer;renderModel(Lnet/minecraft/class_1087;...)V"
 * </pre>
 *
 * <p>{@code require = 0} is kept deliberately: a reshaped method on a future Sodium should cost the
 * player the reveal effect, not a crash on startup. The loudness that {@code require = 0} gives up is
 * bought back at build time instead - Loom's processor resolves this target and this descriptor while
 * compiling, and the {@code verifySodiumHookMapping} task in {@code build.gradle} reads the shipped
 * refmap and fails the build if this exact entry is not in it.
 *
 * <h2>What the two positions are</h2>
 * Read out of {@code ChunkBuilderMeshingTask#execute}: it builds {@code origin} from {@code
 * RenderSection#getOriginX/Y/Z} (world coordinates, the section's corner) and the {@code pos} it hands
 * over from the loop counters masked with 15 (i.e. section-local, 0..15). So the world block a
 * callback is looking at is {@code origin.offset(pos)} - which is also why the publication line and
 * this hook's own entry line can be compared by eye.
 */
@Mixin(targets = "net.caffeinemc.mods.sodium.client.render.chunk.compile.pipeline.BlockRenderer")
public abstract class SodiumBlockRendererMixin {

    @Inject(
            method = "renderModel(Lnet/minecraft/client/resources/model/BakedModel;Lnet/minecraft/world/level/block/state/BlockState;Lnet/minecraft/core/BlockPos;Lnet/minecraft/core/BlockPos;)V",
            at = @At("HEAD"),
            cancellable = true,
            require = 0)
    private void redstonecircuit$skipDrawnHost(BakedModel model, BlockState state, BlockPos pos,
                                               BlockPos origin, CallbackInfo callback) {
        // Unconditional and first, once per hook: this is the line that separates "the injection point
        // was never resolved" from "it was resolved and the block was recognised". Nothing else in the
        // log can, and it prints the coordinates that decide the second case.
        ShaderCompat.noteSodiumHookEntered(pos, origin);
        if (ShaderCompat.hidesHostCube(origin.offset(pos))) {
            ShaderCompat.noteHookUsed("sodium");
            callback.cancel();
            return;
        }
        // Not expected, given the two positions' meaning above - but this is the reading the hook used
        // to accept, and dropping it silently on a future Sodium that changes which argument is local
        // would trade a working feature for a tidy comment. It is kept, it still cancels, and it says
        // so in the log when it is the one that matched.
        if (ShaderCompat.hidesHostCube(pos)) {
            ShaderCompat.noteSodiumLocalReading(pos, origin);
            callback.cancel();
        }
    }
}
